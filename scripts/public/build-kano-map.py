"""Build the Kano State LGA map used on the public landing page.

Usage:
  python3 -I scripts/public/build-kano-map.py <adm1.geojson> <adm2.geojson> src/lib/public/kano-map.ts

Inputs are geoBoundaries Nigeria ADM1/ADM2 (simplified) GeoJSON, source GRID3,
licence CC BY 4.0: https://www.geoboundaries.org/api/current/gbOpen/NGA/ADM2/
Keeps the LGAs whose centroid falls inside Kano State, projects them
(equirectangular, cos-latitude corrected), simplifies (Douglas–Peucker) and
writes SVG path data.
"""
import json
import math
import sys

WIDTH = 560.0
TOLERANCE = 0.9  # px after projection


def rings_of(geom):
    if geom["type"] == "Polygon":
        return [geom["coordinates"]]
    return geom["coordinates"]


def area(ring):
    return 0.5 * sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]))


def centroid(geom):
    best = max(rings_of(geom), key=lambda poly: abs(area(poly[0])))[0]
    a = area(best) or 1e-12
    cx = sum((x1 + x2) * (x1 * y2 - x2 * y1) for (x1, y1), (x2, y2) in zip(best, best[1:] + best[:1])) / (6 * a)
    cy = sum((y1 + y2) * (x1 * y2 - x2 * y1) for (x1, y1), (x2, y2) in zip(best, best[1:] + best[:1])) / (6 * a)
    return cx, cy


def inside(pt, geom):
    x, y = pt
    for poly in rings_of(geom):
        ring = poly[0]
        hit = False
        for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
            if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
                hit = not hit
        if hit:
            return True
    return False


def dp(points, tol):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-12
    far, idx = 0.0, 0
    for i, (x, y) in enumerate(points[1:-1], start=1):
        d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / norm
        if d > far:
            far, idx = d, i
    if far <= tol:
        return [points[0], points[-1]]
    return dp(points[: idx + 1], tol)[:-1] + dp(points[idx:], tol)


def main(adm1_path, adm2_path, out_path):
    adm1 = json.load(open(adm1_path))
    kano = next(f for f in adm1["features"] if f["properties"]["shapeName"] == "Kano")["geometry"]
    adm2 = json.load(open(adm2_path))
    lgas = [f for f in adm2["features"] if inside(centroid(f["geometry"]), kano)]

    xs = [x for f in lgas for poly in rings_of(f["geometry"]) for x, _ in poly[0]]
    ys = [y for f in lgas for poly in rings_of(f["geometry"]) for _, y in poly[0]]
    lat0 = (min(ys) + max(ys)) / 2
    k = math.cos(math.radians(lat0))
    minx, maxy = min(xs) * k, max(ys)
    scale = WIDTH / ((max(xs) - min(xs)) * k)
    height = (max(ys) - min(ys)) * scale

    def proj(x, y):
        return ((x * k - minx) * scale, (maxy - y) * scale)

    def path(geom):
        parts = []
        for poly in rings_of(geom):
            ring = [proj(x, y) for x, y in poly[0]]
            if ring[0] == ring[-1]:
                ring = ring[:-1]
            # A closed ring has no baseline: split it at the point farthest from the start.
            far = max(range(len(ring)), key=lambda i: math.dist(ring[0], ring[i]))
            ring = dp(ring[: far + 1], TOLERANCE)[:-1] + dp(ring[far:] + [ring[0]], TOLERANCE)[:-1]
            if len(ring) < 4:
                continue
            parts.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in ring) + "Z")
        return "".join(parts)

    out = []
    for f in sorted(lgas, key=lambda f: f["properties"]["shapeName"]):
        cx, cy = proj(*centroid(f["geometry"]))
        out.append({"name": f["properties"]["shapeName"], "d": path(f["geometry"]), "cx": round(cx, 1), "cy": round(cy, 1)})

    with open(out_path, "w") as fh:
        fh.write("// Generated by scripts/public/build-kano-map.py. Do not edit by hand.\n")
        fh.write("// Kano State LGA boundaries: geoBoundaries (GRID3), CC BY 4.0.\n\n")
        fh.write(f'export const KANO_VIEWBOX = "0 0 {WIDTH:.0f} {height:.0f}";\n\n')
        fh.write("export type KanoLga = { name: string; d: string; cx: number; cy: number };\n\n")
        fh.write("export const KANO_LGAS: KanoLga[] = " + json.dumps(out, indent=1) + ";\n")
    print(f"{len(out)} LGAs, viewBox {WIDTH:.0f}x{height:.0f}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
